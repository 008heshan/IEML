/**
 * "这条错误其实是**用户自己取消**的" —— 判据只有这一处。
 *
 * ★★ 2026-09-24（C-26 修复）
 *
 *   用户点「取消」之后，流程里抛出来的是一条错误（Rust 侧是
 *   `NetError::Cancelled` = 「任务被取消」，浏览器演示桥是「已取消」），
 *   而安装页的 `catch` 原来**一律弹红色「安装失败：任务被取消」** ——
 *   把自己刚做的操作说成故障，用户会以为"取消了还出错，是不是坏了"。
 *
 *   取消 = 正常结果，该说的是"已停下、已下载的文件保留"。
 *
 * ## 为什么必须是一处判据
 *
 *   两个调用点（整合包安装 `DownloadPage`、版本安装 `InstallComposer`）
 *   都要判同一件事，而两边字符串来源不同（Rust / 浏览器桥）。
 *   分开写迟早只改一处 —— 这个仓库已经为"两套判据"付过好几次代价。
 */

/** 这条错误信息是"用户自己取消了"吗？ */
export function isCancellation(message: string): boolean {
  /*
   * 三个来源都认：
   *   · Rust `NetError::Cancelled` → 「任务被取消」
   *   · 浏览器演示桥                 → 「已取消」
   *   · 兜底英文                     → cancelled / canceled
   */
  return /任务被取消|已取消|cancell?ed/i.test(message);
}
