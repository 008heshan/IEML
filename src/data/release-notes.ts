/**
 * 更新日志的**说人话版本**（用户：「更新日志要去 AI 味，说人话」）。
 *
 * ## ★★ 格式：这是**模板本身**（用户 2026-09-24 定下，是必读篇目）
 *
 * 每一版固定五段，**顺序就是显示顺序；没有内容的段不写**（不是留空标题）：
 *
 * ```
 * 新增了 / 修复了 / 优化了 / 删除了 / 修改了
 * ```
 *
 * 三条硬规矩（写新条目前先读这三条）：
 *
 *   ① **每条开头重复一遍类别词**（用户点名要的）——
 *      段标题是「修复了」，条目就写「修复了 下载页的标题栏被封面糊住」。
 *      这样单摘一条出去也知道它属于哪一类，不必回头看段标题。
 *   ② **言简意赅**：一条一件事、一句话说完；**不写括号里的解释与本条的好处**
 *      （「（玻璃只做透明和折射，不给内容染色）」这种 —— 用户明确说不要）。
 *   ③ **不写假话**：没做的、只在某一台上做过一次的、只是"不再复现"的，
 *      都不许写成"已修复"。写过一次假承诺的代价见下面那段更正记录。
 *   ④ **不写归属**：不写"你报的 / 报上来的 / 你点出来的"这类话 ——
 *      只写"改了什么"，不写"这是谁发现的"。（2026-09-25 用户：
 *      「更新日志不要写我报上来的」。）★ 它与"不吹自己"是同一个方向：
 *      读者关心的是变化，不是功劳簿。
 *   ⑤ ★★ **不写实现细节**（2026-09-26 用户看着 rc.10 的「新增了」三条问
 *      「**这些适合进更新日志吗**」）：命令名、测试文件名、判据条数、退出码、
 *      仓库路径这类东西**玩家一个都用不上** —— 它们写在**提交信息**与**文件注释**里。
 *      ★ 踩过的原话长这样：「新增了后端命令 `fetch_update_notes`：匿名读更新通道的清单」、
 *        「新增了判据 `tests/release-notes.test.mjs`（17 条…），并进了 `verify`（30 → 31 项）」。
 *      ★★ 这条规矩对 **`CHANGELOG.md` 最新那一节同样成立** —— 发布脚本把那一节
 *         **原文**当 `notes` 推到清单，玩家的更新提示里看到的就是它。
 *         （门禁只守得住本文件；改 CHANGELOG 最新一节时要自己记得。）
 *   ⑥ ★★ **底层改动合为一条**（2026-09-27 用户：「如果我们对启动器底层进行修改，
 *      这些的部分合为一条：**修改了 若干启动器底层事项**」；随后又点明为什么：
 *      「也就是我们没有对启动器进行实质性修改，但也得单独开个版本来发布，
 *      所以，就合为一条」）。
 *      ⇒ 一版里如果**没有玩家能看见的变化**（改注释、清死代码、重构、门禁与 CI、
 *        文档口径、版本号管道……），**不要一条条列**，就写这一条：
 *        `修改了 若干启动器底层事项`
 *      ★ 判断标准只有一句：**玩家能不能看见/感觉到**。
 *        看得见的（文案、行为、性能、新功能）各自成条；看不见的合成一条。
 *      ★ 反过来也成立：**合成一条不等于可以偷偷夹带**玩家能看见的变化 ——
 *        那属于"不写假话"（第 ③ 条）。
 *
 * `NoteGroupTitle` 是这五段的**唯一来源**：段名写错会被 `tsc` 直接拦住；
 * 上面六条里 ①~⑤ 由 `tools/check-release-notes.mjs` 守着（进了 `node tools/verify.mjs` 门禁），
 * ⑥ 守不住（"这是不是底层改动"机器判不了），门禁只会在**全篇都是底层痕迹**时给一句提示。
 *
 * ## 为什么不用仓库里的 `CHANGELOG.md`
 *
 * 那份是**给开发者看的工程记录**：里面全是"根因是…""真机断言 132 条""ADR-059"这种话。
 * 它对维护有用，但对用户是噪音 —— 用户想知道的是「这一版改了什么、我能不能用上」，
 * 不是我们怎么验的。所以这里**另写一份面向用户的**。
 *
 * ★ 其余仍适用的老规矩：
 *   · 一条只说**一件事**，用用户的话说（"整合包点不开"而不是"面板在视口外"）；
 *   · 不写"已优化""体验更佳"这种空话 —— 要能对上具体现象；
 *   · 不吹自己（不写"完美解决""彻底修复"）；
 *   · 修的是我们自己的 bug 就直说，不用"优化了逻辑"含糊过去。
 *
 * ★★ 2026-09-24 更正两处**与实现不符**的旧条目（用户看出来的）：
 *   · `beta.55` 那条写着「绿宝石皮肤文件的导入与导出（皮肤页）」——
 *     全仓库没有这个功能，也**没有"皮肤页"**（皮肤是账号面板里按 Mojang 官方接口
 *     拉真实皮肤、本地裁头部）。已改成事实。
 *   · `rc.1` 那条写着「版本名统一成「Minecraft 1.12.2 ：原版」这种写法」——
 *     界面上其实写的是「1.20.1 · 原版」（没有 "Minecraft" 前缀、也没有全角冒号）。已改成事实。
 *   ★ 教训：这份文件是**用户向说明**，它同样受"不许有假承诺"的约束 ——
 *     写之前要去界面上核一眼，不能凭印象写。
 */

/** 更新日志的**固定五段**（顺序即显示顺序；没有内容的段不写） */
export type NoteGroupTitle = '新增了' | '修复了' | '优化了' | '删除了' | '修改了';

export interface ReleaseNote {
  /** 版本号（与 package.json 一致） */
  version: string;
  /** 日期 */
  date: string;
  /** 这一版的头条（一句话） */
  headline?: string;
  /** 分组：新增了 / 修复了 / 优化了 / 删除了 / 修改了 */
  groups: Array<{ title: NoteGroupTitle; items: string[] }>;
}

