/**
 * 更新日志的**说人话版本**（用户：「更新日志要去 AI 味，说人话」）。
 *
 * ## 为什么不用仓库里的 `CHANGELOG.md`
 *
 * 那份是**给开发者看的工程记录**（310 KB）：里面全是"★★ 根因是…""真机断言 132 条"
 * "ADR-059 第十七节"这种话。它对维护有用，但对用户是噪音 ——
 * 用户想知道的是「这一版修好了什么、我能不能用上」，不是我们怎么验的。
 *
 * 所以这里**另写一份面向用户的**，一条一句话，说"你遇到的那件事现在怎么样了"。
 * ★ 规矩（写新条目时照这个来）：
 *   · 一条只说**一件事**，用用户的话说（"整合包点不开"而不是"面板在视口外"）；
 *   · 不写"已优化""体验更佳"这种空话 —— 要能对上具体现象；
 *   · 不吹自己（不写"完美解决""彻底修复"）；
 *   · 修的是我们自己的 bug 就直说，不用"优化了逻辑"含糊过去。
 */

export interface ReleaseNote {
  /** 版本号（与 package.json 一致） */
  version: string;
  /** 日期 */
  date: string;
  /** 这一版的头条（一句话） */
  headline?: string;
  /** 分组：新东西 / 修好了 / 改了 */
  groups: Array<{ title: string; items: string[] }>;
}

